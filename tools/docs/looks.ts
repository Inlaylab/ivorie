// Theme options for the docs playground, from the same data the registry uses.
import { readFileSync } from 'node:fs';
import { RADII, type DialKey, type Preset } from '../../projects/cli/src/preset.ts';
import { LEGACY_THEMES, themeDials } from '../registry/build.ts';
import { THEME_INFO, THEMES, THEME_ORDER, type ThemeInfo } from '../registry/themes.ts';
import { themeNames } from '../styles/hooks.ts';

// shadcn/ui order, not alphabetical: the playground shows them like this.
const BASE_COLORS = ['neutral', 'stone', 'zinc', 'mauve', 'olive', 'mist', 'taupe'];
// Accents in hue order (shadcn lists them A–Z), so the swatch row reads as a spectrum.
const ACCENTS = ['red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose'];

interface BaseColor {
  name: string;
  title: string;
  light: Record<string, string>;
  dark: Record<string, string>;
}
interface FontOption {
  name: string;
  title: string;
  type: string;
  family: string;
  dependency: string;
}

export function looksData(): {
  baseColors: BaseColor[];
  accents: BaseColor[];
  fonts: FontOption[];
  radii: Record<string, string | null>;
  themes: Record<string, Preset>;
  themeOrder: readonly string[];
  themeDials: Record<string, DialKey[]>;
  legacyThemes: string[];
  themeInfo: Record<string, ThemeInfo>;
} {
  const baseColors = BASE_COLORS.map((name) => {
    const c = JSON.parse(readFileSync(`tools/registry/base-colors/${name}.json`, 'utf8'));
    return { name, title: c.title, light: c.light, dark: c.dark };
  });
  const accents = ACCENTS.map((name) => {
    const c = JSON.parse(readFileSync(`tools/registry/accent-colors/${name}.json`, 'utf8'));
    return { name, title: c.title, light: c.light, dark: c.dark };
  });
  const fonts = JSON.parse(readFileSync('tools/registry/fonts.json', 'utf8')).map(
    ({ name, title, type, family, dependency }: FontOption) => ({ name, title, type, family, dependency }),
  );
  const names = themeNames();
  return {
    baseColors,
    accents,
    fonts,
    radii: RADII,
    themes: THEMES,
    themeOrder: THEME_ORDER,
    themeDials: Object.fromEntries(names.map((name) => [name, themeDials(name)])),
    legacyThemes: LEGACY_THEMES,
    themeInfo: THEME_INFO,
  };
}

export function looksModule(): string {
  const d = looksData();
  const j = (v: unknown) => JSON.stringify(v, null, 2);
  return `// Generated by tools/docs/build.ts. Do not edit.
import type { DialKey, Preset } from '../app/playground/preset-code';

export interface BaseColor {
  name: string;
  title: string;
  light: Record<string, string>;
  dark: Record<string, string>;
}
export interface FontOption {
  name: string;
  title: string;
  type: 'sans' | 'serif' | 'mono';
  family: string;
  dependency: string;
}

export const BASE_COLORS: BaseColor[] = ${j(d.baseColors)};

/** Accent colors: primary, secondary, chart and sidebar-primary over a base color. */
export const ACCENTS: BaseColor[] = ${j(d.accents)};

export const FONTS: FontOption[] = ${j(d.fonts)};

export const RADII: Record<string, string | null> = ${j(d.radii)};

/** Each theme's defaults, in picker order. \`glass\` is the default. */
export const THEME_ORDER = ${j(d.themeOrder)} as const;
export type ThemeName = (typeof THEME_ORDER)[number];
export const THEMES: Record<ThemeName, Preset> = ${j(d.themes)};

/** The dials each theme takes. */
export const THEME_DIALS: Record<string, DialKey[]> = ${j(d.themeDials)};

/** Themes that still work but leave in 2.0. Hidden from pickers unless in use. */
export const LEGACY_THEMES: string[] = ${j(d.legacyThemes)};

export interface ThemeInfo {
  label: string;
  group: 'own' | 'classic' | 'legacy';
  tag: string;
  note: string;
}
/** Every theme with a CSS file, legacy included, in picker order. */
export const THEME_INFO: Record<string, ThemeInfo> = ${j(d.themeInfo)};
`;
}
