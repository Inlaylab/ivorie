// Compiles apps/docs/content/*.md into lazy TS page modules in apps/docs/src/generated/.
// Also publishes the CLI registry at /r/ and the components.json schema at /schema/.
// Usage: node tools/docs/build.ts
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { buildPage, createHighlighter, createRenderer, parseFrontmatter } from './content.ts';
import type { DocPage } from '../../apps/docs/src/app/content/types.ts';
import { build as buildRegistry } from '../registry/build.ts';

const CONTENT = 'apps/docs/content';
const DEMOS = 'apps/docs/src/app/demos';
const OUT = 'apps/docs/src/generated';

const errors: string[] = [];

// Demo name = file name without extension.
const demos = new Map<string, string>();
const demoPaths = new Map<string, string>();
const demoFiles = (existsSync(DEMOS) ? readdirSync(DEMOS, { recursive: true, encoding: 'utf8' }) : [])
  .filter((f) => f.endsWith('.ts') && !f.endsWith('.spec.ts'))
  .map((f) => f.replaceAll('\\', '/'))
  .sort();
for (const file of demoFiles) {
  const name = basename(file, '.ts');
  if (demoPaths.has(name)) {
    errors.push(`duplicate demo "${name}": ${demoPaths.get(name)} and ${file}`);
    continue;
  }
  demoPaths.set(name, file);
  demos.set(name, readFileSync(join(DEMOS, file), 'utf8').replaceAll('\r\n', '\n'));
}

const render = createRenderer(await createHighlighter());
const pages: DocPage[] = [];
const orders = new Map<string, number>();
for (const file of readdirSync(CONTENT).filter((f) => f.endsWith('.md') && !f.startsWith('_'))) {
  const slug = basename(file, '.md');
  const md = readFileSync(join(CONTENT, file), 'utf8');
  try {
    pages.push(buildPage({ slug, file: `${CONTENT}/${file}`, md, demos, render }));
    orders.set(slug, parseFrontmatter(md, file).data.order ?? 0);
  } catch (e) {
    errors.push((e as Error).message);
  }
}

if (errors.length) {
  errors.forEach((e) => console.error(`error: ${e}`));
  process.exit(1);
}

// Guides first by order, then components A–Z.
pages.sort((a, b) =>
  a.section !== b.section
    ? a.section === 'guide'
      ? -1
      : 1
    : (orders.get(a.slug)! - orders.get(b.slug)!) || a.title.localeCompare(b.title),
);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'pages'), { recursive: true });
const HEADER = '// Generated by tools/docs/build.ts. Do not edit.\n';

for (const page of pages) {
  writeFileSync(
    join(OUT, 'pages', `${page.slug}.ts`),
    `${HEADER}import type { DocPage } from '../../app/content/types';\n\n` +
      `export default ${JSON.stringify(page, null, 2)} satisfies DocPage;\n`,
  );
}

const entries = pages.map((p) => {
  const meta = { slug: p.slug, title: p.title, description: p.description, section: p.section };
  const fields = Object.entries(meta).map(([k, v]) => `${k}: ${JSON.stringify(v)}`);
  return (
    `  {\n    ${fields.join(',\n    ')},\n    order: ${orders.get(p.slug)},\n` +
    `    load: () => import('./pages/${p.slug}').then((m) => m.default),\n  },`
  );
});
writeFileSync(
  join(OUT, 'pages.ts'),
  `${HEADER}import type { PageEntry } from '../app/content/types';\n\n` +
    `export const PAGES: PageEntry[] = [\n${entries.join('\n')}\n];\n`,
);

const loaders = [...demoPaths].map(
  ([name, file]) =>
    `  '${name}': () => import('../app/demos/${file.replace(/\.ts$/, '')}').then((m) => m.default),`,
);
writeFileSync(
  join(OUT, 'demos.ts'),
  `${HEADER}import type { DemoLoader } from '../app/content/types';\n\n` +
    `export const DEMOS: Record<string, DemoLoader> = {\n${loaders.join('\n')}\n};\n`,
);

buildRegistry('apps/docs/public/r');
mkdirSync('apps/docs/public/schema', { recursive: true });
copyFileSync('projects/cli/schema/components.schema.json', 'apps/docs/public/schema/components.json');

console.log(`docs: ${pages.length} pages, ${demos.size} demos`);
