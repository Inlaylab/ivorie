// Compiles apps/docs/content/*.md into lazy TS page modules in apps/docs/src/generated/.
// Also writes the playground look options (looks.ts) and publishes the CLI registry at /r/ and the components.json schema at /schema/.
// Usage: node tools/docs/build.ts
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync as write } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { buildPage, createHighlighter, createRenderer, parseFrontmatter } from './content.ts';
import type { DocPage } from '../../apps/docs/src/app/content/types.ts';
import { build as buildRegistry } from '../registry/build.ts';
import { blockMeta, listBlocks } from '../registry/items.ts';
import { looksModule } from './looks.ts';
import { cliPin, packStyles, siteLook, siteStyle } from './site-style.ts';
import { parseChangelog } from './changelog.ts';
import { DEFAULT_PRESET } from '../../projects/cli/src/preset.ts';

const CONTENT = 'apps/docs/content';
const DEMOS = 'apps/docs/src/app/demos';
const OUT = 'apps/docs/src/generated';

const errors: string[] = [];

// Demo name = file name without extension.
const demos = new Map<string, string>();
const demoPaths = new Map<string, string>();
const demoFiles = (existsSync(DEMOS) ? readdirSync(DEMOS, { recursive: true, encoding: 'utf8' }) : [])
  .filter((f) => f.endsWith('.ts') && !f.endsWith('.spec.ts'))
  .map((f) => f.replaceAll('\\', '/'))
  .sort();
for (const file of demoFiles) {
  const name = basename(file, '.ts');
  if (demoPaths.has(name)) {
    errors.push(`duplicate demo "${name}": ${demoPaths.get(name)} and ${file}`);
    continue;
  }
  demoPaths.set(name, file);
  demos.set(name, readFileSync(join(DEMOS, file), 'utf8').replaceAll('\r\n', '\n'));
}

const render = createRenderer(await createHighlighter());
const pages: DocPage[] = [];
const orders = new Map<string, number>();
const soon = new Set<string>();
const start = new Set<string>();
for (const file of readdirSync(CONTENT).filter((f) => f.endsWith('.md') && !f.startsWith('_'))) {
  const slug = basename(file, '.md');
  const md = readFileSync(join(CONTENT, file), 'utf8');
  try {
    pages.push(buildPage({ slug, file: `${CONTENT}/${file}`, md, demos, render }));
    const { data } = parseFrontmatter(md, file);
    orders.set(slug, data.order ?? 0);
    if (data.soon) soon.add(slug);
    if (data.group === 'start') start.add(slug);
  } catch (e) {
    errors.push((e as Error).message);
  }
}

if (errors.length) {
  errors.forEach((e) => console.error(`error: ${e}`));
  process.exit(1);
}

// Guides first by order, then components A–Z, then the chart gallery A–Z.
const SECTIONS = ['guide', 'component', 'charts'];
pages.sort(
  (a, b) =>
    SECTIONS.indexOf(a.section) - SECTIONS.indexOf(b.section) ||
    orders.get(a.slug)! - orders.get(b.slug)! ||
    a.title.localeCompare(b.title),
);

// The folder is never emptied first: a running `ng serve` would lose its imports (TS2307) until the files are back.
// Files are rewritten only when they change; what this run did not write is stale and goes at the end.
mkdirSync(join(OUT, 'pages'), { recursive: true });
const stale = new Set(readdirSync(OUT, { recursive: true, withFileTypes: true }).filter((f) => f.isFile()).map((f) => resolve(f.parentPath, f.name)));
function writeFileSync(path: string, data: string): void {
  stale.delete(resolve(path));
  if (!existsSync(path) || readFileSync(path, 'utf8') !== data) write(path, data);
}
const HEADER = '// Generated by tools/docs/build.ts. Do not edit.\n';

for (const page of pages) {
  writeFileSync(
    join(OUT, 'pages', `${page.slug}.ts`),
    `${HEADER}import type { DocPage } from '../../app/content/types';\n\n` +
      `export default ${JSON.stringify(page, null, 2)} satisfies DocPage;\n`,
  );
}

const entries = pages.map((p) => {
  const meta = { slug: p.slug, title: p.title, description: p.description, section: p.section };
  const fields = Object.entries(meta).map(([k, v]) => `${k}: ${JSON.stringify(v)}`);
  return (
    `  {\n    ${fields.join(',\n    ')},\n    order: ${orders.get(p.slug)},\n` +
    (soon.has(p.slug) ? '    soon: true,\n' : '') +
    (start.has(p.slug) ? "    group: 'start',\n" : '') +
    `    load: () => import('./pages/${p.slug}').then((m) => m.default),\n  },`
  );
});
writeFileSync(
  join(OUT, 'pages.ts'),
  `${HEADER}import type { PageEntry } from '../app/content/types';\n\n` +
    `export const PAGES: PageEntry[] = [\n${entries.join('\n')}\n];\n`,
);

const loaders = [...demoPaths].map(
  ([name, file]) =>
    `  '${name}': () => import('../app/demos/${file.replace(/\.ts$/, '')}').then((m) => m.default),`,
);
writeFileSync(
  join(OUT, 'demos.ts'),
  `${HEADER}import type { DemoLoader } from '../app/content/types';\n\n` +
    `export const DEMOS: Record<string, DemoLoader> = {\n${loaders.join('\n')}\n};\n`,
);

writeFileSync(join(OUT, 'looks.ts'), looksModule());
// The changelog page: CHANGELOG.md, one entry per release, notes rendered like any docs page.
const releases = parseChangelog(readFileSync('CHANGELOG.md', 'utf8')).map(({ body, ...r }) => ({ ...r, html: render(body).html }));
writeFileSync(
  join(OUT, 'changelog.ts'),
  `${HEADER}export interface ChangelogRelease {
  version: string;
  date: string;
  title: string;
  html: string;
}

export const CHANGELOG: ChangelogRelease[] = ${JSON.stringify(releases, null, 2)};
`,
);
// The site theme is the one on <body> in index.html (DEFAULT_THEME in appearance-options.ts names the same).
const siteStyleName = /<body class="theme-([a-z]+)"/.exec(readFileSync('apps/docs/src/index.html', 'utf8'))?.[1];
if (!siteStyleName) throw new Error('docs: no theme-<name> class on <body> in apps/docs/src/index.html');
if (siteStyleName !== DEFAULT_PRESET.theme) throw new Error(`docs: <body> has theme-${siteStyleName}, the default theme is ${DEFAULT_PRESET.theme}`);
writeFileSync(join(OUT, 'site-style.css'), siteStyle(siteStyleName));
// The site's colors: the default preset as `ivorie init` writes it (DOCS_PRESET is THEMES.slate, the same preset).
writeFileSync(join(OUT, 'site-look.css'), siteLook(DEFAULT_PRESET));
write('apps/docs/src/styles.pack.css', packStyles(readFileSync('apps/docs/src/styles.css', 'utf8'), siteStyleName));
// Copied commands name the CLI minor: the site can deploy before npm has the release, and an older CLI
// reads the new flags another way.
writeFileSync(join(OUT, 'cli.ts'), `${HEADER}export const IVORIE = '${cliPin(JSON.parse(readFileSync('projects/cli/package.json', 'utf8')).version)}';\n`);

// Blocks: meta and a lazy page loader in blocks.ts; the highlighted files per block in blocks/<name>.ts,
// so the code loads only on its block page.
const GROUPS: Record<string, string> = { login: 'Login', signup: 'Sign up', sidebar: 'Sidebar', dashboard: 'Dashboard', stats: 'Data', usage: 'Data', status: 'Data' };
const pascal = (name: string) => name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const blocks = listBlocks();
mkdirSync(join(OUT, 'blocks'), { recursive: true });
for (const b of blocks) {
  const files = b.files.map((f) => {
    const fence = '`'.repeat(Math.max(3, ...(f.content.match(/`+/g) ?? []).map((r) => r.length + 1)));
    return { path: f.name, code: f.content, html: render(`${fence}ts\n${f.content}\n${fence}`).html };
  });
  writeFileSync(join(OUT, 'blocks', `${b.name}.ts`), `${HEADER}export default ${JSON.stringify(files, null, 2)};\n`);
}
const blockEntries = blocks.map((b) => {
  const { title, description } = blockMeta(b);
  return (
    `  {\n    name: '${b.name}',\n    title: ${JSON.stringify(title)},\n    description: ${JSON.stringify(description)},\n` +
    `    group: '${GROUPS[b.name.split('-')[0]]}',\n` +
    `    load: () => import('../../../../projects/blocks/${b.name}/${b.name}').then((m) => m.${pascal(b.name)}),\n` +
    `    files: () => import('./blocks/${b.name}').then((m) => m.default),\n  },`
  );
});
writeFileSync(
  join(OUT, 'blocks.ts'),
  `${HEADER}import type { BlockEntry } from '../app/content/types';\n\n` +
    `export const BLOCKS: BlockEntry[] = [\n${blockEntries.join('\n')}\n];\n`,
);

buildRegistry('apps/docs/public/r');
for (const path of stale) rmSync(path);

mkdirSync('apps/docs/public/schema', { recursive: true });
copyFileSync('projects/cli/schema/components.schema.json', 'apps/docs/public/schema/components.json');

console.log(`docs: ${pages.length} pages, ${demos.size} demos`);
