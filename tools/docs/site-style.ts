// The docs site's own copy of its default style, kept out of previews of another style. The site sets
// `theme-<default>` on <body>, and a preview (Home wall, playground stage, their overlays) is a
// `.docs-preview.theme-<name>` element inside it, marked `docs-other` when its theme is not the site's (PlaygroundLook). The library style would still match inside, and fill in
// what the previewed style leaves out (a rounded thumb in sera, glass panes under nova). Every rule here
// skips those previews. A component page's demo card is a `.docs-preview` with no mark: it keeps the site style.
// The mark is one short class on purpose: it is repeated on every generated rule, and the initial CSS has a budget.
import { readFileSync } from 'node:fs';
import { RADII, chartSource, contrastVars, dialVars, lookVars, type Preset } from '../../projects/cli/src/preset.ts';
import { themeDials } from '../registry/build.ts';

/** A preview in another style than the site's. */
export const OTHER_PREVIEW = '.docs-other';
export const NOT_PREVIEW = `:not(${OTHER_PREVIEW} *)`;
/** Own styles set tokens on every element; inside another style's preview nothing may be set, the root included. */
export const EVERY_ELEMENT = `& :where(*:not(${OTHER_PREVIEW}, ${OTHER_PREVIEW} *)) {`;

// A selector line that ends on a hook: `.cn-x {`, `& .cn-x {`, `& .cn-a .cn-b {`, or an item of a list (`.cn-x,`).
const HOOK_SELECTOR = /^(\s+(?:& )?[^@\n]*\.cn-[a-z0-9-]+)( \{|,)$/gm;

export function siteStyle(name: string, css = readFileSync(`projects/ui/styles/theme-${name}.css`, 'utf8')): string {
  return css
    .replace(HOOK_SELECTOR, `$1${NOT_PREVIEW}$2`)
    .replaceAll('& :where(*) {', EVERY_ELEMENT)
    // The site never uses the 1.5 class or a renamed theme's old classes; each alias in every compiled
    // selector costs initial CSS.
    .replace(new RegExp(`:is\\(\\.theme-${name}, \\.style-${name}(, \\.(theme|style)-[a-z]+)*\\) \\{`), `.theme-${name} {`);
}

type Vars = Record<string, string>;
const colors = (dir: string, name: string): { light: Vars; dark: Vars } => JSON.parse(readFileSync(`tools/registry/${dir}/${name}.json`, 'utf8'));
const css = (sel: string, vars: Vars) => `${sel} {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;

/**
 * The site's look from a preset, the same merge `ivorie init` writes: colors and radius on :root and
 * .dark, so the chrome and the demo frames are the default theme as installed. Dials (density, …) go on the
 * component-page demo frames only (.docs-demo; playground stages get them inline): a compact --spacing on
 * :root would shrink the site layout itself.
 */
export function siteLook(p: Preset): string {
  const base = colors('base-colors', p.baseColor);
  const accent = p.accent === 'base' ? undefined : colors('accent-colors', p.accent);
  const chart = chartSource(p) === 'base' ? base : colors('accent-colors', chartSource(p));
  const dials = themeDials(p.theme);
  const mode = (m: 'light' | 'dark') => {
    const vars = lookVars(base[m], accent?.[m], chart[m], p.menuAccent);
    return dials.includes('contrast') ? { ...vars, ...contrastVars(vars, p.contrast) } : vars;
  };
  const radius = RADII[p.radius];
  return [
    `/* Generated by tools/docs/build.ts from DOCS_PRESET (${p.theme}, ${p.accent}). Do not edit. */\n`,
    css(':root', { ...mode('light'), ...(radius ? { '--radius': radius } : {}) }),
    css('.dark', mode('dark')),
    css('.docs-demo', dialVars(p, dials)),
  ].join('\n');
}

/**
 * The pack build's stylesheet (ng build docs -c production,pack): styles.css with the library from the
 * installed tarball. The site theme comes from the package as is (the site's own copy is a docs build
 * artifact), and the library source is never scanned, so a packaging mistake shows. tools/docs/build.ts
 * writes it; a test keeps it equal.
 */
export function packStyles(styles: string, theme: string): string {
  const swap = (from: string, to: string) => {
    if (!styles.includes(from)) throw new Error(`packStyles: styles.css no longer has ${from}`);
    styles = styles.replace(from, to);
  };
  swap('@import "../../../projects/ui/styles/theme.css";', '@import "@inlaylab/ivorie/styles/theme.css";');
  swap('@import "./generated/site-style.css";', `@import "@inlaylab/ivorie/styles/theme-${theme}.css";`);
  swap('@source "../../../projects/ui";', '@source not "../../../projects/ui";');
  return `/* Generated by tools/docs/build.ts from styles.css (packStyles). Do not edit. The pack build: the library comes
   from the installed npm tarball. Its theme.css @source scans the package. */
${styles}`;
}

/** The CLI command the docs copy: pinned to the minor (ivorie@1.6), or the exact version for a prerelease (2.0.0-beta.1). */
export const cliPin = (version: string): string => `npx ivorie@${version.includes('-') ? version : version.split('.').slice(0, 2).join('.')}`;
