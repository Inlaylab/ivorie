// Builds projects/ui/styles/style-<name>.css from shadcn's style file, keeping only the hooks we use.
// Usage: node tools/styles/sync.ts maia   (needs the .ref/shadcn clone, see docs/CONVENTIONS.md)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { STYLES, uiHooks } from './hooks.ts';

const SHADCN_STYLES = '.ref/shadcn/apps/v4/registry/styles';

export interface Rule {
  mark: string;
  hook: string;
  /** The rule's lines, re-based to a 2-space indent (shadcn's shape). */
  lines: string[];
}

/** Reads `.cn-x {` rules and MARK comments at the given indent: 2 for shadcn files, 4 for ours. */
export function parse(css: string, indent = 2): Rule[] {
  const pad = ' '.repeat(indent);
  const rebase = (line: string) => (!line.trim() ? '' : line.startsWith(pad) ? '  ' + line.slice(indent) : line);
  const rules: Rule[] = [];
  let mark = '';
  let rule: Rule | undefined;
  for (const line of css.split('\n')) {
    const m = line.startsWith(pad) ? /^\/\* MARK: (.+) \*\/$/.exec(line.slice(indent)) : null;
    if (m) mark = m[1];
    else if (rule) {
      rule.lines.push(rebase(line));
      if (line === pad + '}') rule = undefined;
    } else {
      const r = line.startsWith(pad) ? /^\.(cn-[a-z0-9-]+) \{$/.exec(line.slice(indent)) : null;
      if (r) rules.push((rule = { mark, hook: r[1], lines: [rebase(line)] }));
    }
  }
  return rules;
}

/** Top-level lines that open a rule parse() cannot read, e.g. `.cn-a, .cn-b {`. They are dropped. */
export function unknownShapes(css: string): string[] {
  return css
    .split('\n')
    .filter((l) => /^ {2}\S.*\{$/.test(l) && !/^ {2}\.(cn-[a-z0-9-]+) \{$/.test(l))
    .map((l) => l.trim());
}

// Opt-in looks: shadcn applies these only for a non-default preset option (menuColor *-translucent).
// Copying them would make every menu see-through, and the blur layer does not follow a scrolled list.
const OPT_IN = new Set(['cn-menu-translucent']);

/** Drops commented-out rules (sera: input-group-addon-align-inline-*). Plain comments stay. */
export function stripComments(css: string): string {
  return css.replace(/\/\*[\s\S]*?\*\//g, (c) => (c.includes('{') ? '' : c));
}

export function buildStyle(name: string, shadcnCss: string, hooks: Set<string>): string {
  const rules = parse(stripComments(shadcnCss)).filter((r) => hooks.has(r.hook) && !OPT_IN.has(r.hook));
  return renderStyle(name, rules, hooks, [
    `Ivorie style: ${name}. Generated by tools/styles/sync.ts. Do not edit by hand.`,
    `Rules copied from shadcn/ui (MIT): apps/v4/registry/styles/style-${name}.css.`,
  ]);
}

/** The style file: header, rules under their MARKs, extras, then an empty rule for each hook with no rule. */
export function renderStyle(name: string, rules: Rule[], hooks: Set<string>, header: string[], extras: string[] = []): string {
  const covered = new Set(rules.map((r) => r.hook));
  const out: string[] = [];
  let mark = '';
  for (const rule of rules) {
    if (rule.mark !== mark) {
      if (out.length) out.push('');
      out.push(`    /* MARK: ${(mark = rule.mark)} */`);
    } else out.push('');
    out.push(...rule.lines.map((l) => '  ' + l));
  }
  if (extras.length) {
    if (out.length) out.push('');
    out.push('    /* MARK: Style extras */', ...extras);
  }
  const missing = [...hooks].filter((h) => !covered.has(h)).sort();
  if (missing.length) {
    if (out.length) out.push('');
    out.push(`    /* MARK: No rule in ${name} */`, ...missing.map((h) => `    .${h} {}`));
  }
  return [
    '/*',
    ...header.map((l) => ` * ${l}`),
    ' * Components carry the cn-* hooks; this file gives them their look.',
    " * In @layer components, so a user's utility classes win.",
    ' */',
    '@layer components {',
    `  .style-${name} {`,
    ...out,
    '  }',
    '}',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const name = process.argv[2];
  if (!/^[a-z]+$/.test(name ?? '')) throw new Error('usage: node tools/styles/sync.ts <style name>');
  const css = readFileSync(join(SHADCN_STYLES, `style-${name}.css`), 'utf8').replaceAll('\r\n', '\n');
  for (const line of unknownShapes(stripComments(css))) console.warn(`warn: skipped rule ${line}`);
  writeFileSync(join(STYLES, `style-${name}.css`), buildStyle(name, css, uiHooks()));
}
