// Builds projects/ui/styles/style-<name>.css from an own style file and a synced base style.
// Usage: node tools/styles/derive.ts glass   (or --all for every tools/styles/own/*.css)
// The own file starts with `/* @base nova */`. Its `.cn-x {` rules replace the base rule for that hook.
// Every other top-level block (`& {`, `.dark & {`, `& .cn-x {`, `.cn-a, .cn-b {`, `@supports`, `@media`)
// is copied as an extra after the rules: it adds to the base rules instead of replacing them.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { STYLES, uiHooks } from './hooks.ts';
import { type Rule, parse, renderStyle } from './sync.ts';

export const OWN = 'tools/styles/own';

export interface Own {
  base: string;
  rules: Rule[];
  extras: string[];
}

export function parseOwn(css: string): Own {
  const lines = css.split('\n');
  const base = /^\/\* @base ([a-z]+) \*\/$/.exec(lines[0])?.[1];
  if (!base) throw new Error('own style: first line must be /* @base <name> */');
  const extras: string[] = [];
  const rules: string[] = [];
  let depth = 0;
  let extra = false;
  let comment = false;
  let list = false; // inside a selector list, before its `{`
  for (const line of lines.slice(1)) {
    if (depth === 0 && !list) {
      // Between blocks: blank lines and comments are dropped. A lone `.cn-x {` is a replace rule.
      if (comment || line.startsWith('/*')) {
        comment = !line.includes('*/');
        continue;
      }
      if (!line.trim()) continue;
      extra = !/^\.cn-[a-z0-9-]+ \{$/.test(line);
      if (extra && extras.length) extras.push('');
    }
    list = depth === 0 && line.trimEnd().endsWith(',');
    depth += (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
    (extra ? extras : rules).push(line);
  }
  return { base, rules: parse(rules.join('\n'), 0), extras };
}

export function deriveStyle(name: string, ownCss: string, baseCss: string, hooks: Set<string>): string {
  const own = parseOwn(ownCss);
  const replace = new Map(own.rules.map((r) => [r.hook, r]));
  for (const hook of replace.keys()) if (!hooks.has(hook)) throw new Error(`own style ${name}: unknown hook .${hook}`);
  const rules = parse(baseCss, 4)
    .filter((r) => hooks.has(r.hook))
    .map((r) => ({ ...r, lines: replace.get(r.hook)?.lines ?? r.lines }));
  const seen = new Set(rules.map((r) => r.hook));
  // An own rule for a hook the base leaves empty goes at the end, under its own MARK.
  for (const r of own.rules) if (!seen.has(r.hook)) rules.push({ ...r, mark: `Only in ${name}` });
  return renderStyle(
    name,
    rules,
    hooks,
    [
      `Ivorie style: ${name}. Generated by tools/styles/derive.ts from tools/styles/own/${name}.css + style-${own.base}.css. Do not edit by hand.`,
      `Own rules replace the ${own.base} rule for the same hook. Base rules from shadcn/ui (MIT).`,
    ],
    own.extras.map((l) => (l.trim() ? '    ' + l : '')),
  );
}

function derive(name: string): void {
  const own = readFileSync(join(OWN, `${name}.css`), 'utf8').replaceAll('\r\n', '\n');
  const base = readFileSync(join(STYLES, `style-${parseOwn(own).base}.css`), 'utf8').replaceAll('\r\n', '\n');
  writeFileSync(join(STYLES, `style-${name}.css`), deriveStyle(name, own, base, uiHooks()));
}

if (import.meta.main) {
  const arg = process.argv[2] ?? '';
  const names = arg === '--all' ? readdirSync(OWN).filter((f) => f.endsWith('.css')).map((f) => f.slice(0, -4)) : [arg];
  for (const name of names) {
    if (!/^[a-z]+$/.test(name)) throw new Error('usage: node tools/styles/derive.ts <style name>|--all');
    derive(name);
  }
}
